export function t(key, params) {
  const dict = messages[locale.value] ?? messages.ko
  let text = dict[key] ?? messages.ko[key] ?? key
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value))
    }
  }
  return text
}
