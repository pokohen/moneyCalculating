import { ref } from "vue";

export const LOCALES = ["ko", "ja", "en"];
export const LOCALE_NAMES = { ko: "한국어", ja: "日本語", en: "English" };

/* 언어는 각 HTML의 lang 속성에서 읽는다.
   /            → ko
   /ja/         → ja
   /en/         → en
   빌드 때 언어별 HTML을 따로 뽑기 때문에 화면 코드는 이 값만 보면 된다. */
function detect() {
  const tag = document.documentElement.lang?.slice(0, 2);
  return LOCALES.includes(tag) ? tag : "ko";
}

export const locale = ref(detect());

/** 지금 주소에서 언어 칸만 바꾼 경로. 하위 경로에 배포해도 그대로 동작한다. */
export function pathFor(target) {
  const parts = window.location.pathname.split("/").filter(Boolean);
  if (parts[parts.length - 1] === "index.html") parts.pop();
  if (LOCALES.includes(parts[parts.length - 1])) parts.pop();
  const root = `/${parts.length ? `${parts.join("/")}/` : ""}`;
  return target === "ko" ? root : `${root}${target}/`;
}

